export function findUberPin(name: string) {
  if (!name) return null;
  return UBER_PINS.find(p => name.includes(p.match)) || null;
}

export function getUberDeepLink(dropoffName?: string, coords?: Coordinates | null, address?: string): string {
  const pin = dropoffName ? findUberPin(dropoffName) : null;
  const nickname = pin ? pin.nickname : (dropoffName || 'Destination');
  const addr = pin ? pin.address : (address || dropoffName || '');
  const lat = pin ? pin.lat : (coords && coords.lat);
  const lng = pin ? pin.lng : (coords && coords.lng);
  let url = `https://m.uber.com/ul/?action=setPickup&client_id=dcfamilytrip&pickup=my_location` +
    `&dropoff[nickname]=${encodeURIComponent(nickname)}&dropoff[formatted_address]=${encodeURIComponent(addr)}`;
  if (lat && lng) url += `&dropoff[latitude]=${lat}&dropoff[longitude]=${lng}`;
  return url;
}

export async function geocodeAddress(text: string): Promise<Coordinates | null> {
  try {
    const r = await fetch('https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&countrycodes=us&q=' + encodeURIComponent(text));
    const data = await r.json();
    if (data && data[0]) return { lat: parseFloat(data[0].lat), lng: parseFloat(data[0].lon) };
  } catch (e) {}
  return null;
}

