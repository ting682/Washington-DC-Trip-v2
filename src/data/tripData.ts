export function calcDistanceMiles(c1: Coordinates | null, c2: Coordinates | null): number {
  if (!c1 || !c2) return 1.0;
  const R = 3958.8;
  const dLat = (c2.lat - c1.lat) * Math.PI / 180;
  const dLon = (c2.lng - c1.lng) * Math.PI / 180;
  const a = Math.sin(dLat/2) * Math.sin(dLat/2) +
            Math.cos(c1.lat * Math.PI / 180) * Math.cos(c2.lat * Math.PI / 180) * 
            Math.sin(dLon/2) * Math.sin(dLon/2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
  return (R * c) * 1.25;
}

export function computeTripDay(dayData: DayData, dIdx: number, customDinner?: DinnerItem | null) {
  const computed = { ...dayData };
  if (customDinner) {
    computed.dinner = customDinner;
  }

  const items = [...computed.fixedStopsBefore];

  if (computed.dinner && computed.afternoonStop) {
    const distToDinner = calcDistanceMiles(computed.afternoonStop.coords, computed.dinner.coords);
    const walkTimeMins = Math.round(distToDinner * 20);

    if (walkTimeMins > 20) {
      const driveMins = Math.max(8, Math.round(distToDinner * 4.5 + 5));
      const estLow = Math.max(14, Math.round(10 + distToDinner * 3.5));
      const estHigh = estLow + 8;

      items.push({
        type: 'transit-uber',
        time: '~5:15 PM',
        duration: `${driveMins} min`,
        title: `UberXL to Dinner (${computed.dinner.name})`,
        location: `${computed.afternoonStop.name} to ${computed.dinner.name}`,
        desc: `Distance is ${distToDinner.toFixed(1)} miles (~${walkTimeMins} min walk). Auto-routed to UberXL to avoid tiring out the kids.`,
        uberMeta: { estFare: `$${estLow}–$${estHigh}`, time: `${driveMins} min`, seats: 'Seats 5' },
        destCoords: computed.dinner.coords || undefined,
        destName: computed.dinner.name,
        destAddress: computed.dinner.location,
        icon: 'fa-car-side',
      });
    } else {
      const steps = Math.round(distToDinner * 2150);
      items.push({
        type: 'transit-walk',
        time: '~5:40 PM',
        duration: `${walkTimeMins} min`,
        title: `Walk to Dinner (${computed.dinner.name})`,
        location: `${computed.afternoonStop.name} to ${computed.dinner.name}`,
        desc: `Easy, scenic family stroll (${distToDinner.toFixed(2)} miles). Flat sidewalks for the kids.`,
        walkMeta: { steps: `~${steps.toLocaleString()} steps`, dist: `${distToDinner.toFixed(2)} mi`, time: `${walkTimeMins} min` },
        icon: 'fa-person-walking',
      });
    }

    items.push({
      type: 'food',
      time: computed.dinner.time,
      duration: computed.dinner.duration || '1 hr 30 min',
      title: `Dinner: ${computed.dinner.name}`,
      location: computed.dinner.location,
      website: computed.dinner.website,
      desc: computed.dinner.desc,
      isDinner: true,
      dayIndex: dIdx,
      icon: 'fa-utensils',
    });

    const distToHotel = calcDistanceMiles(computed.dinner.coords, HOTEL_COORDS);
    const returnWalkMins = Math.round(distToHotel * 20);

    if (returnWalkMins > 20) {
      const driveMins = Math.max(8, Math.round(distToHotel * 4.2 + 4));
      const estLow = Math.max(14, Math.round(10 + distToHotel * 3.2));
      const estHigh = estLow + 8;

      items.push({
        type: 'transit-uber',
        time: '~7:15 PM',
        duration: `${driveMins} min`,
        title: 'UberXL back to Holiday Inn',
        location: `${computed.dinner.name} to Holiday Inn`,
        desc: `${distToHotel.toFixed(1)} miles back to 1501 Rhode Island Ave NW. Rest of the evening open.`,
        uberMeta: { estFare: `$${estLow}–$${estHigh}`, time: `${driveMins} min`, seats: 'UberXL' },
        destCoords: HOTEL_COORDS,
        destName: 'Holiday Inn Washington-Central',
        icon: 'fa-car-side',
      });
    } else {
      const steps = Math.round(distToHotel * 2150);
      items.push({
        type: 'transit-walk',
        time: '~7:15 PM',
        duration: `${returnWalkMins} min`,
        title: 'Stroll back to Holiday Inn',
        location: `${computed.dinner.name} to Hotel`,
        desc: `Short evening stroll (${distToHotel.toFixed(2)} miles) back to 1501 Rhode Island Ave NW.`,
        walkMeta: { steps: `~${steps.toLocaleString()} steps`, dist: `${distToHotel.toFixed(2)} mi`, time: `${returnWalkMins} min` },
        icon: 'fa-person-walking',
      });
    }
  }

  if (computed.bedtime) {
    items.push({
      type: 'bedtime',
      time: computed.bedtime.time,
      duration: computed.bedtime.duration,
      title: computed.bedtime.title,
      desc: computed.bedtime.desc,
      icon: 'fa-moon',
    });
  }

  computed.items = items;
  return computed;
}

